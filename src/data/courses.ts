/** Stable id for compare/enquiry state — unique per row. */
export function courseId(c: Course): string {
  return `${c.stream}__${c.name}__${c.university}`.replace(/\s+/g, '-');
}

export function getCoursesByStream(stream: StreamSlug): Course[] {
  return COURSES.filter((c) => c.stream === stream);
}

export function courseCount(stream: StreamSlug): number {
  return getCoursesByStream(stream).length;
}

/** Distinct universities (with a representative location) for a stream. */
export function getUniversitiesByStream(
  stream: StreamSlug,
): { university: string; location: string }[] {
  const seen = new Map<string, string>();
  for (const c of getCoursesByStream(stream)) {
    if (!seen.has(c.university)) seen.set(c.university, c.location);
  }
  return Array.from(seen, ([university, location]) => ({ university, location }));
}
